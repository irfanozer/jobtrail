CREATE TABLE job_sources (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(120) NOT NULL, provider VARCHAR(30) NOT NULL, board_key VARCHAR(100) NOT NULL,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, last_attempt_at TIMESTAMP WITH TIME ZONE,
 last_success_at TIMESTAMP WITH TIME ZONE, last_error VARCHAR(500), job_count INTEGER NOT NULL DEFAULT 0,
 CONSTRAINT uq_source_board UNIQUE(provider, board_key)
);
CREATE TABLE jobs (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 source_id BIGINT NOT NULL REFERENCES job_sources(id),
 external_id VARCHAR(255) NOT NULL, title VARCHAR(500) NOT NULL, company VARCHAR(200) NOT NULL,
 location VARCHAR(1000) NOT NULL, description TEXT NOT NULL, url VARCHAR(2000) NOT NULL,
 workplace VARCHAR(30) NOT NULL, level VARCHAR(30) NOT NULL, status VARCHAR(30) NOT NULL DEFAULT 'NEW',
 published_at TIMESTAMP WITH TIME ZONE, source_updated_at TIMESTAMP WITH TIME ZONE,
 first_seen_at TIMESTAMP WITH TIME ZONE NOT NULL, last_seen_at TIMESTAMP WITH TIME ZONE NOT NULL,
 active BOOLEAN NOT NULL DEFAULT TRUE, content_hash VARCHAR(64) NOT NULL,
 CONSTRAINT uq_job_source_external UNIQUE(source_id, external_id)
);
CREATE INDEX idx_jobs_source_active ON jobs(source_id, active);
CREATE INDEX idx_jobs_first_seen ON jobs(first_seen_at);
CREATE INDEX idx_jobs_status ON jobs(status);

